// The Wii's DSI entry for guest memory (mem_wii.c).
//
// libogc's general exception entry (PPCExcptEntryGeneral) jumps here with translation on and
// external interrupts off, r11/r12 saved in SPRG0/SPRG1 (r11 = the exception id, r12 = this
// address), CR in __ppc_excpt_buf+8 and SRR0/SRR1 in __ppc_excpt_buf+0/+4 (SRR0/SRR1 themselves
// are clobbered). r1 is the interrupted code's stack.
//
// Fast path, in exception context: a frame below r1 for the volatile registers, then
// wl_xb_dsi_fast(DAR, DSISR), which maps a first-touched guest page (or both pages of a
// misaligned access) and returns 1; the access is retried with rfi. It returns 0 for a fault on
// guest addresses it cannot map (a device, a page not committed): the slow path moves the fault
// out of exception context into a trampoline that runs wl_xb_dsi_slow(frame) in the faulting
// code's own context (device emulation, or the crash report) and resumes at the frame's pc. It
// returns 2 for a fault outside the guest span: the handler that was installed before (libogc's
// panic path) gets it with the entry state rebuilt (r11 = 3, CR0 not "eq" so it stays on this
// stack).
//
// The slow path is the lead's prototype (scratchpad proto_mmu/dsi.S), proven in Dolphin with
// MMU emulation: FP state survives a thousand faults.
//
//
// Written as top-level assembly in a C file so the build needs no assembler language of its
// own (registers by number: the assembler is not given -mregnames). Frame offsets: the fast frame keeps r0, r3..r10, LR, CTR, XER; the slow frame is the
// DsiFrame of mem_wii.c.
#if defined(__wii__)
__asm__(
    "    .section .text.wl_xb_dsi_entry,\"ax\",@progbits\n"
    "    .globl wl_xb_dsi_entry\n"
    "wl_xb_dsi_entry:\n"
    "    addi    12, 1, -0x60\n"
    "    rlwinm  12, 12, 0, 0, 27\n"
    "    stw     1, 0(12)\n"
    "    stw     0, 0x10(12)\n"
    "    stw     3, 0x14+0*4(12)\n"
    "    stw     4, 0x14+1*4(12)\n"
    "    stw     5, 0x14+2*4(12)\n"
    "    stw     6, 0x14+3*4(12)\n"
    "    stw     7, 0x14+4*4(12)\n"
    "    stw     8, 0x14+5*4(12)\n"
    "    stw     9, 0x14+6*4(12)\n"
    "    stw     10, 0x14+7*4(12)\n"
    "    mflr    0\n"
    "    stw     0, 0x34(12)\n"
    "    mfctr   0\n"
    "    stw     0, 0x38(12)\n"
    "    mfxer   0\n"
    "    stw     0, 0x3c(12)\n"
    "    mr      1, 12\n"
    "    mfdar   3\n"
    "    mfdsisr 4\n"
    "    bl      wl_xb_dsi_fast\n"
    "    mr      11, 3\n"
    "    lwz     0, 0x34(1)\n"
    "    mtlr    0\n"
    "    lwz     0, 0x38(1)\n"
    "    mtctr   0\n"
    "    lwz     0, 0x3c(1)\n"
    "    mtxer   0\n"
    "    lwz     0, 0x10(1)\n"
    "    lwz     3, 0x14+0*4(1)\n"
    "    lwz     4, 0x14+1*4(1)\n"
    "    lwz     5, 0x14+2*4(1)\n"
    "    lwz     6, 0x14+3*4(1)\n"
    "    lwz     7, 0x14+4*4(1)\n"
    "    lwz     8, 0x14+5*4(1)\n"
    "    lwz     9, 0x14+6*4(1)\n"
    "    lwz     10, 0x14+7*4(1)\n"
    "    lwz     1, 0(1)\n"
    "    cmpwi   11, 1\n"
    "    beq     1f\n"
    "    cmpwi   11, 2\n"
    "    beq     2f\n"
    "    b       wl_xb_dsi_slow_entry\n"
    "1:\n"
    "    lis     11, __ppc_excpt_buf@ha\n"
    "    addi    11, 11, __ppc_excpt_buf@l\n"
    "    lwz     12, 8(11)\n"
    "    mtcr    12\n"
    "    lwz     12, 0(11)\n"
    "    mtsrr0  12\n"
    "    lwz     12, 4(11)\n"
    "    mtsrr1  12\n"
    "    mfsprg  11, 0\n"
    "    mfsprg  12, 1\n"
    "    rfi\n"
    "2:\n"
    "    lis     12, g_xb_prev_dsi@ha\n"
    "    lwz     12, g_xb_prev_dsi@l(12)\n"
    "    mtsrr0  12\n"
    "    mfmsr   12\n"
    "    mtsrr1  12\n"
    "    li      11, 3\n"
    "    cmpwi   11, 0\n"
    "    rfi\n"
    "wl_xb_dsi_slow_entry:\n"
    "    addi    12, 1, -0x180\n"
    "    rlwinm  12, 12, 0, 0, 27\n"
    "    stw     0, 0x010+0*4(12)\n"
    "    stw     1, 0x010+1*4(12)\n"
    "    stw     1, 0(12)\n"
    "    stmw    2, 0x010+2*4(12)\n"
    "    mfsprg  11, 0\n"
    "    stw     11, 0x010+11*4(12)\n"
    "    mfsprg  11, 1\n"
    "    stw     11, 0x010+12*4(12)\n"
    "    lis     11, __ppc_excpt_buf@ha\n"
    "    addi    11, 11, __ppc_excpt_buf@l\n"
    "    lwz     0, 0(11)\n"
    "    stw     0, 0x090(12)\n"
    "    lwz     0, 4(11)\n"
    "    stw     0, 0x094(12)\n"
    "    mtsrr1  0\n"
    "    lwz     0, 8(11)\n"
    "    stw     0, 0x098(12)\n"
    "    mflr    0\n"
    "    stw     0, 0x09c(12)\n"
    "    mfctr   0\n"
    "    stw     0, 0x0a0(12)\n"
    "    mfxer   0\n"
    "    stw     0, 0x0a4(12)\n"
    "    mfdar   0\n"
    "    stw     0, 0x0a8(12)\n"
    "    mfdsisr 0\n"
    "    stw     0, 0x0ac(12)\n"
    "    mr      1, 12\n"
    "    lis     11, wl_xb_dsi_trampoline@ha\n"
    "    addi    11, 11, wl_xb_dsi_trampoline@l\n"
    "    mtsrr0  11\n"
    "    rfi\n"
    "    .section .text.wl_xb_dsi_trampoline,\"ax\",@progbits\n"
    "wl_xb_dsi_trampoline:\n"
    "    stfd    0,  0x0b8+0*8(1)\n"
    "    stfd    1,  0x0b8+1*8(1)\n"
    "    stfd    2,  0x0b8+2*8(1)\n"
    "    stfd    3,  0x0b8+3*8(1)\n"
    "    stfd    4,  0x0b8+4*8(1)\n"
    "    stfd    5,  0x0b8+5*8(1)\n"
    "    stfd    6,  0x0b8+6*8(1)\n"
    "    stfd    7,  0x0b8+7*8(1)\n"
    "    stfd    8,  0x0b8+8*8(1)\n"
    "    stfd    9,  0x0b8+9*8(1)\n"
    "    stfd    10, 0x0b8+10*8(1)\n"
    "    stfd    11, 0x0b8+11*8(1)\n"
    "    stfd    12, 0x0b8+12*8(1)\n"
    "    stfd    13, 0x0b8+13*8(1)\n"
    "    mffs    0\n"
    "    stfd    0,  0x0b0(1)\n"
    "    addi    3, 1, 0\n"
    "    stwu    1, -16(1)\n"
    "    bl      wl_xb_dsi_slow\n"
    "    addi    1, 1, 16\n"
    "    mfmsr   3\n"
    "    rlwinm  3, 3, 0, 17, 15\n"
    "    mtmsr   3\n"
    "    isync\n"
    "    lfd     0,  0x0b0(1)\n"
    "    mtfsf   0xff, 0\n"
    "    lfd     0,  0x0b8+0*8(1)\n"
    "    lfd     1,  0x0b8+1*8(1)\n"
    "    lfd     2,  0x0b8+2*8(1)\n"
    "    lfd     3,  0x0b8+3*8(1)\n"
    "    lfd     4,  0x0b8+4*8(1)\n"
    "    lfd     5,  0x0b8+5*8(1)\n"
    "    lfd     6,  0x0b8+6*8(1)\n"
    "    lfd     7,  0x0b8+7*8(1)\n"
    "    lfd     8,  0x0b8+8*8(1)\n"
    "    lfd     9,  0x0b8+9*8(1)\n"
    "    lfd     10, 0x0b8+10*8(1)\n"
    "    lfd     11, 0x0b8+11*8(1)\n"
    "    lfd     12, 0x0b8+12*8(1)\n"
    "    lfd     13, 0x0b8+13*8(1)\n"
    "    lwz     0, 0x090(1)\n"
    "    mtsrr0  0\n"
    "    lwz     0, 0x094(1)\n"
    "    mtsrr1  0\n"
    "    lwz     0, 0x098(1)\n"
    "    mtcr    0\n"
    "    lwz     0, 0x09c(1)\n"
    "    mtlr    0\n"
    "    lwz     0, 0x0a0(1)\n"
    "    mtctr   0\n"
    "    lwz     0, 0x0a4(1)\n"
    "    mtxer   0\n"
    "    lwz     0, 0x010+0*4(1)\n"
    "    lmw     2, 0x010+2*4(1)\n"
    "    lwz     1, 0x010+1*4(1)\n"
    "    rfi\n"
);
#endif
