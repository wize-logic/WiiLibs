"""Links a program while part of it is not written yet.

A port or a program in bring-up calls more than it provides. This links the program once; if
the linker reports undefined symbols, it writes a C file defining each one as a function that
stops the program naming it (by default wl_platform_missing_symbol, wl/platform/stop.h, which
shows the name on the Wii's screen and waits for HOME), compiles it, and links again. The names
go to --report, one a line: what the program still lacks. Once the list is empty this is an
ordinary link, and the report is empty.

A data symbol stubbed this way is a function, which is wrong, and only safe because the
program stops as soon as it calls into any of them. A data symbol that is read before then
is named with --data NAME[:BYTES], which defines it as that many zero bytes (16 if no size is
given, aligned to 16) instead.

usage: link_stubs.py --linker CC --compiler CC [--cflags FLAGS] [--ldflags FLAGS] [--libs FLAGS]
                     --stubs FILE.c --report FILE.txt --output FILE
                     [--stop-function NAME] [--data NAME[:BYTES]]... @objects.rsp | OBJECT...

--linker and --compiler are commands (the compiler driver usually does both). --cflags,
--ldflags and --libs are single arguments holding shell-quoted flags: the compiler's for the
stub file, the linker's before the objects, and the libraries after them. An object argument
starting with @ is a response file of shell-quoted paths (as ninja writes them). The stub
file's object is written beside it with the extension .o. The stop function takes the symbol's
name as a `const char *`.
"""

import argparse
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

# GNU ld quotes with ` and ' (or the typographic quotes in a UTF-8 locale), lld with ' only
UNDEFINED = re.compile(r"undefined (?:reference to|symbol:?) [`'‘’]?([A-Za-z_.$][^'’\s]*)")
IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
DEFAULT_STOP_FUNCTION = "wl_platform_missing_symbol"
DATA_DEFAULT_BYTES = 16


def link(linker, ldflags, objects, libs, output):
    command = [*shlex.split(linker), *shlex.split(ldflags), "-o", str(output), *objects, *shlex.split(libs)]
    return subprocess.run(command, capture_output=True, text=True, env=_env())


def _env():
    env = dict(os.environ)
    env["LC_ALL"] = "C"  # (the linker's messages in a form to match)
    return env


def undefined_symbols(text):
    """The names an ld or lld error text reports as undefined, sorted and without repeats."""
    return sorted(set(UNDEFINED.findall(text)))


def parse_data(items):
    """--data NAME[:BYTES] values as {name: bytes}."""
    sizes = {}
    for item in items:
        name, _, size = item.partition(":")
        if not IDENTIFIER.match(name) or (size and not size.isdigit()) or (size and int(size) == 0):
            raise ValueError(f"--data {item!r}: want NAME or NAME:BYTES (a positive number)")
        sizes[name] = int(size) if size else DATA_DEFAULT_BYTES
    return sizes


def stub_source(names, stop_function, data, origin="tools/link_stubs.py"):
    """The C file that defines every name: a function that stops, or zeroed storage for a data name."""
    lines = [f"/* generated by {origin}: the symbols this program does not provide yet */", "",
             f"void {stop_function}(const char *name) __attribute__((noreturn));", ""]
    for name in names:
        if name in data:
            lines.append(f"char {name}[{data[name]}] __attribute__((aligned(16)));")
        else:
            lines.append(f'void {name}(void) {{ {stop_function}("{name}"); }}')
    return "\n".join(lines) + "\n"


def expand_objects(arguments):
    # (ninja's response file quotes the paths with spaces, as a shell would)
    return [obj for argument in arguments
            for obj in (shlex.split(Path(argument[1:]).read_text()) if argument.startswith("@") else [argument])]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--linker", required=True)
    parser.add_argument("--compiler", required=True)
    parser.add_argument("--cflags", default="")
    parser.add_argument("--ldflags", default="")
    parser.add_argument("--libs", default="")
    parser.add_argument("--stubs", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--stop-function", default=DEFAULT_STOP_FUNCTION,
                        help="the function every stub calls with its name (default: %(default)s)")
    parser.add_argument("--data", action="append", default=[], metavar="NAME[:BYTES]",
                        help="a data symbol: zero bytes instead of a function")
    parser.add_argument("--name", default="link_stubs.py", help="the tool's name in messages")
    parser.add_argument("objects", nargs="*")
    args = parser.parse_args(argv)
    if not IDENTIFIER.match(args.stop_function):
        parser.error(f"--stop-function {args.stop_function!r} is not a C identifier")
    try:
        data = parse_data(args.data)
    except ValueError as error:
        parser.error(str(error))
    objects = expand_objects(args.objects)

    result = link(args.linker, args.ldflags, objects, args.libs, args.output)
    if result.returncode == 0:
        args.report.write_text("")
        return 0
    missing = undefined_symbols(result.stderr)
    stubbable = [name for name in missing if IDENTIFIER.match(name)]
    if not missing or len(stubbable) != len(missing):
        # (a failure that is not only undefined symbols)
        sys.stderr.write(result.stderr)
        return result.returncode or 1

    args.stubs.write_text(stub_source(stubbable, args.stop_function, data))
    stub_object = args.stubs.with_suffix(".o")
    compiled = subprocess.run([*shlex.split(args.compiler), *shlex.split(args.cflags), "-w", "-c",
                               str(args.stubs), "-o", str(stub_object)], capture_output=True, text=True)
    if compiled.returncode != 0:
        sys.stderr.write(compiled.stderr)
        return compiled.returncode

    result = link(args.linker, args.ldflags, [*objects, str(stub_object)], args.libs, args.output)
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        return result.returncode
    args.report.write_text("".join(f"{name}\n" for name in stubbable))
    print(f"{args.name}: {len(stubbable)} symbols stubbed (listed in {args.report})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
